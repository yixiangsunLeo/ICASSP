#!/usr/bin/env python
"""Generate the external-baseline configs `bl_<ds>_zs_lr1e4.yaml` from the main-run configs.

    python scripts/make_baseline_configs.py            # writes code/configs/experiments/bl_*.yaml
    python scripts/make_baseline_configs.py --print    # show what would be written
    python scripts/make_baseline_configs.py --check    # exit 1 if the files on disk differ

Protocol (docs/PROTOCOL_external_baselines.md, decision D-034): the 2024-2025 baselines
TCFormer / LaBraM / EEGPT / CBraMod — and, on 3C, the ANN baselines ATCNet / EEG-Deformer /
FBCNet that the earlier 3C run trained with patience 100 — are added to the SAME experiment
as the spiking main run: same folds, same trials, same normalization (per-trial z-score, no
alignment), same recipe (Adam 1e-4 / batch 128 / patience 25 on val macro-F1 / seed 0), and
their cells are written into the same run directory, so `analyze_snn_round.py` pairs them
per subject with every other entry without any extra plumbing.

Hence each `bl_*` config is the corresponding `snn_<ds>_zs_lr1e4.yaml` with exactly three
edits: `experiment.source_config`, `models`, and `train.micro_batch_per_model` (gradient
accumulation for the transformer models so the *effective* batch stays 128; they have no
BatchNorm, so accumulation is exact). Everything else is copied verbatim and asserted equal
by `tests/models/test_external_integration.py`. The `snn_*.yaml` files are never edited
(the running jobs read them at start-up).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
EXP = ROOT / "code" / "configs" / "experiments"

#: the four external baselines (docs/PROTOCOL_external_baselines.md §2)
EXTERNAL = ["tcformer", "labram", "eegpt", "cbramod"]
#: 3C only: ANN baselines whose published-table numbers came from the patience-100 run
#: (`paper_baseline_3c_821_v1`); re-run here under the shared recipe so the 3C column is on
#: one protocol. EEGNeX / EEGNet are already re-run by the main run itself.
ANN_FILL_3C = ["atcnet", "eeg_deformer", "fbcnet"]

#: micro-batches for the pretrained transformers (effective batch stays 128 via accumulation;
#: LayerNorm-only models, so the optimisation is identical). Set from the adapters' memory
#: estimates; TCFormer keeps the full batch (it has BatchNorm and is small).
MICRO_BATCH = {"labram": 64, "eegpt": 32, "cbramod": 64}

SOURCES = {
    "wbci2c": ("snn_wbci2c_zs_lr1e4.yaml", EXTERNAL),
    "shu":    ("snn_shu_zs_lr1e4.yaml", EXTERNAL),
    "wbci3c": ("snn_wbci3c_zs_lr1e4.yaml", EXTERNAL + ANN_FILL_3C),
}

#: keys that MUST be identical between a bl_* config and its snn_* source
PROTECTED_TOP = ("run_id", "data", "cross_subject", "eval", "checkpoints", "output", "model_params")
#: train keys allowed to differ (only this one)
TRAIN_FREE = ("micro_batch_per_model",)


def build(ds: str) -> tuple[Path, dict]:
    src_name, models = SOURCES[ds]
    src = EXP / src_name
    with open(src, "r", encoding="utf-8") as f:
        cfg = yaml.safe_load(f)
    out_name = f"bl_{ds}_zs_lr1e4.yaml"
    cfg["experiment"]["source_config"] = f"configs/experiments/{out_name}"
    cfg["models"] = list(models)
    cfg["train"]["micro_batch_per_model"] = {m: MICRO_BATCH[m] for m in models if m in MICRO_BATCH}
    return EXP / out_name, cfg


def header(ds: str, src_name: str, models: list[str]) -> str:
    fill = "" if ds != "wbci3c" else (
        "#   + the ANN baselines ATCNet / EEG-Deformer / FBCNet, whose earlier 3C numbers used\n"
        "#   patience 100 (paper_baseline_3c_821_v1); re-run here under the shared recipe.\n")
    return (
        "# =====================================================================\n"
        f"# EXTERNAL BASELINES (D-034) — generated by scripts/make_baseline_configs.py from\n"
        f"#   {src_name}. DO NOT EDIT BY HAND: regenerate, then run\n"
        "#   pytest tests/models/test_external_integration.py (asserts protocol identity).\n"
        "# Identical to the source except `experiment.source_config`, `models` and\n"
        "# `train.micro_batch_per_model`. Cells land in the SAME run directory as the spiking\n"
        "# main run, so every entry is paired per (split, fold, subject) with the 18 ANN\n"
        "# benchmark entries and the SNNs. Protocol: docs/PROTOCOL_external_baselines.md.\n"
        f"# Models: {', '.join(models)}\n"
        f"{fill}"
        "# =====================================================================\n"
    )


def render(ds: str) -> tuple[Path, str]:
    path, cfg = build(ds)
    src_name, models = SOURCES[ds]
    body = yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, default_flow_style=False,
                          width=100)
    return path, header(ds, src_name, models) + body


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--print", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    rc = 0
    for ds in SOURCES:
        path, text = render(ds)
        if args.print:
            print(f"##### {path.relative_to(ROOT)}\n{text}")
            continue
        if args.check:
            on_disk = path.read_text(encoding="utf-8") if path.exists() else None
            ok = on_disk == text
            print(f"{'OK  ' if ok else 'DIFF'} {path.relative_to(ROOT)}")
            rc |= 0 if ok else 1
            continue
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    sys.exit(rc)


if __name__ == "__main__":
    main()
