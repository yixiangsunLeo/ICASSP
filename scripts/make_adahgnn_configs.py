#!/usr/bin/env python
"""Write ``bl_<ds>_adahgnn_zs_lr1e4.yaml`` from the live ``snn_<ds>_zs_lr1e4.yaml``.

Does **not** rewrite D-034 ``bl_*_zs_lr1e4.yaml`` (those files are still being read by
queued relay jobs 71035 / 71223). Cells still land in ``snn_<ds>_zs_lr1e4_v1``.

    python scripts/make_adahgnn_configs.py
    python scripts/make_adahgnn_configs.py --check
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
EXP = ROOT / "code" / "configs" / "experiments"

SOURCES = {
    "wbci2c": "snn_wbci2c_zs_lr1e4.yaml",
    "shu": "snn_shu_zs_lr1e4.yaml",
    "wbci3c": "snn_wbci3c_zs_lr1e4.yaml",
}
PROTECTED_TOP = ("run_id", "data", "cross_subject", "eval", "checkpoints", "output", "model_params")
TRAIN_FREE = ("micro_batch_per_model",)
#: D-040: the adapted model and its mixup arm. The unadapted `adahgnn` is not run.
MODELS = ["adahgnn@mi", "adahgnn@mi_mix"]


def build(ds: str) -> tuple[Path, dict]:
    src_name = SOURCES[ds]
    with open(EXP / src_name, "r", encoding="utf-8") as f:
        cfg = yaml.safe_load(f)
    out_name = f"bl_{ds}_adahgnn_zs_lr1e4.yaml"
    cfg["experiment"]["source_config"] = f"configs/experiments/{out_name}"
    cfg["models"] = list(MODELS)
    cfg["train"]["micro_batch_per_model"] = {}
    return EXP / out_name, cfg


def header(ds: str, src_name: str) -> str:
    return (
        "# =====================================================================\n"
        f"# AdaHGNN-MI (D-037/D-040) — generated by scripts/make_adahgnn_configs.py from\n"
        f"#   {src_name}. DO NOT EDIT BY HAND. Protocol-identical to the source except\n"
        f"#   `experiment.source_config` and `models: {MODELS}`.\n"
        "#   Live D-034 bl_*_zs_lr1e4.yaml files are not touched. Cells land in the SAME run\n"
        "#   directory as the spiking main run. The model has BatchNorm, so there is no\n"
        "#   micro-batch (full recipe batch 128).\n"
        "# =====================================================================\n"
    )


def render(ds: str) -> tuple[Path, str]:
    path, cfg = build(ds)
    body = yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, default_flow_style=False,
                          width=100)
    return path, header(ds, SOURCES[ds]) + body


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--print", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    rc = 0
    for ds in SOURCES:
        path, text = render(ds)
        if args.print:
            print(f"##### {path.relative_to(ROOT)}\n{text}")
            continue
        if args.check:
            on_disk = path.read_text(encoding="utf-8") if path.exists() else None
            ok = on_disk == text
            print(f"{'OK  ' if ok else 'DIFF'} {path.relative_to(ROOT)}")
            rc |= 0 if ok else 1
            continue
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    sys.exit(rc)


if __name__ == "__main__":
    main()
