#!/usr/bin/env python
"""Generate the experiment configs of the spiking-EEGNeX round from one template.

    python scripts/make_snn_configs.py            # writes code/configs/experiments/snn_*.yaml
    python scripts/make_snn_configs.py --print    # show what would be written

Design (docs/PLAN_spiking_eegnex_icassp2027.md §3): every run keeps the benchmark's
cross-subject block (kfold_subject 6:2:2, split_seeds 41/42 — or LOSO for 3C) and recipe
(Adam / batch 128 / patience 25 on macro-F1 / max 500 epochs / seed 0) so that each new entry
is paired, per subject, with the 18 ANN entries of `wbci_2c_cross_subject_bench_v1` /
`shu_cross_subject_bench_v1`. The grid is {dataset} x {normalization: zs | ea} x {lr}.

One config per (dataset, normalization, lr). The learning rate is piloted on SHU (both
values, split 41 only, chosen by *validation* macro-F1); 2C / 3C configs exist for both
values too, only the chosen one is submitted.
"""

from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "code" / "configs" / "experiments"

#: the entries of this round (aliases resolve via code/configs/models/seegnex.yaml, seegnet.yaml)
MODELS = [
    "eegnex",               # ANN parent, re-run in-run for paired best/last/AdaBN + predictions
    "eegnet_official",      # ANN anchor for the alignment arms (EEG-expert review, B4)
    "seegnex@hplif",        # D: direct encoding, T=4, heterogeneous PLIF
    "seegnex@s_lif",        # S: temporal-native, fixed tau
    "seegnex@s_plif",       # S: learnable tau per layer
    "seegnex@s_hplif",      # S: heterogeneous learnable tau  (main model)
    "seegnet@plif",         # spiking EEGNet baseline (D, T=4)
]
#: single-factor ablations of the main model, submitted only if budget allows
ABLATIONS = ["seegnex@s_hplif_afe", "seegnex@s_hplif_spk", "seegnex@s_hplif_causal",
             "seegnex@s_hplif_hard", "seegnex@s_hplif_noinit", "seegnex@s_hplif_noreg",
             "seegnex@s_hplif_all", "seegnex@plif_t8"]

NORMS = {
    "zs":   "per_sample_zscore",                   # benchmark baseline normalization
    # per-session Euclidean Alignment (label-free) + per-trial SCALAR scale (a channel-wise
    # z-score after EA would undo the whitening; EEG-expert review B5)
    "ea":   "ea_session+per_sample_global",
    # same, reference covariance from an 8-30 Hz copy of the trials (mu/beta band; B6)
    "eamu": "ea_session_mu+per_sample_global",
    # EA followed by the benchmark's channel-wise z-score. Theory says the z-score undoes the
    # whitening (EEG review B5); the first completed cells said otherwise (+1pp on 4 folds vs
    # z-score alone), so it stays in the pilot as an empirical arm.
    "eaz":  "ea_session+per_sample_zscore",
}
LRS = {"lr1e4": 1e-4, "lr1e3": 1e-3}

DATASETS = {
    "shu": dict(
        name="shu", manifest="shu_processed_manifest", n_channels=32, n_classes=2,
        out="shu",
        cross_subject={"protocol": "kfold_subject", "n_folds": 5, "val_mode": "subjects",
                       "n_val_subjects": 5, "split_seeds": [41, 42]},
        note="SHU 2022 (25 subjects, 32 ch). 15:5:5 by subject = 6:2:2. Floor effect: chance "
             "band 51.4-53.7%, read 1-2pp differences with care.",
    ),
    "wbci2c": dict(
        name="wbci_shu_2c", manifest="processed_manifest", n_channels=58, n_classes=2,
        out="wbci_shu",
        cross_subject={"protocol": "kfold_subject", "n_folds": 5, "val_mode": "subjects",
                       "n_val_subjects": 10, "split_seeds": [41, 42]},
        note="WBCIC-SHU 2C (51 subjects, 58 ch). 30/31:10:10/11 by subject ~ 6:2:2. The only "
             "cohort powered to detect ~2pp paired differences.",
    ),
    "wbci3c": dict(
        name="wbci_shu_3c", manifest="wbci_3c_processed_manifest", n_channels=58, n_classes=3,
        out="wbci_shu",
        cross_subject={"protocol": "loso", "n_folds": 11, "val_mode": "subjects",
                       "n_val_subjects": 2, "split_seed": 0},
        note="WBCIC-SHU 3C (11 subjects, LOSO, 8:2:1 by subject). Third cohort / 3-class. "
             "Recipe = benchmark recipe (patience 25), so eegnex is re-run here as the paired "
             "reference; paper_baseline_3c_821_v1 (patience 100) is historical only.",
    ),
}

TEMPLATE = """\
experiment:
  name: "foundation_cross_subject"
  source_config: "configs/experiments/{fname}"

# =====================================================================
# SPIKING EEGNeX ROUND (ICASSP 2027) — {ds_key} x {norm_key} x {lr_key}
# Plan: docs/PLAN_spiking_eegnex_icassp2027.md ; generated by scripts/make_snn_configs.py
#
# {note}
#
# NORMALIZATION: {norm_desc}
# LR: {lr}  ({lr_note})
# PAIRING: cross_subject block identical to the 18-entry benchmark -> same folds, same
#   test subjects; every entry here is paired per subject with those 18 ANN entries.
# ADABN: evaluation-time only; adds adabn_* columns (BatchNorm stats re-estimated on each
#   held-out subject's unlabeled trials). Does not touch training or the cell signature.
# =====================================================================

run_id: "{run_id}"

data:
  name: "{name}"
  manifest: "{manifest}"
  status_filter: ["ok"]
  n_channels: {n_channels}
  n_times: 1000
  n_classes: {n_classes}
  sfreq: 250

models: {models}

cross_subject:
{cross_subject}

train:
  optimizer: "adam"
  lr: {lr}
  batch_size: 128
  max_epochs: 500                 # ceiling only; patience binds first
  weight_decay: 0.0
  scheduler: "none"
  grad_clip_norm: 0.0
  monitor: "macro_f1"
  monitor_mode: "max"
  early_stopping_patience: 25
  normalization: "{norm}"
  num_workers: 2
  amp: false
  device: "cuda"
  seeds: [0]
  # curves off: (i) no per-epoch test accuracy is printed while humans watch the pilot
  # (statistics review, model-selection audit), (ii) each extra eval pass re-runs the
  # 1000-step neuron loops. Re-enable for the H4 (overfitting) observation if wanted.
  curves: false
  train_eval_max_trials: 2000
  # T=4 direct encoding stores ~4x the ANN activations; keep the effective batch at 128.
  micro_batch_per_model:
    "seegnex@hplif": 64
    "seegnex@plif": 64
    "seegnex@lif": 64
    "seegnex@plif_t8": 32
    "seegnet@plif": 64

model_params: {{}}

eval:
  metrics: ["accuracy", "macro_f1", "auc", "balanced_accuracy", "cohen_kappa"]
  calibration_metrics: ["nll", "brier", "ece"]
  report_scope: "per_test_subject"
  adabn: true

checkpoints:
  keep: ["best", "last"]
  resume: true

output:
  output_dir: "outputs/experiments/{out}/{run_id}"
  checkpoint_dir: "checkpoints/{out}/{run_id}"
"""


def _yaml_block(d: dict, indent: int = 2) -> str:
    pad = " " * indent
    lines = []
    for k, v in d.items():
        if isinstance(v, list):
            lines.append(f"{pad}{k}: [{', '.join(str(x) for x in v)}]")
        elif isinstance(v, str):
            lines.append(f'{pad}{k}: "{v}"')
        else:
            lines.append(f"{pad}{k}: {v}")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--print", action="store_true")
    ap.add_argument("--with-ablations", action="store_true",
                    help="append the ablation entries to the model list")
    args = ap.parse_args()
    models = MODELS + (ABLATIONS if args.with_ablations else [])
    models_yaml = "[" + ", ".join(f'"{m}"' for m in models) + "]"
    written = []
    for ds_key, ds in DATASETS.items():
        for norm_key, norm in NORMS.items():
            for lr_key, lr in LRS.items():
                run_id = f"snn_{ds_key}_{norm_key}_{lr_key}_v1"
                fname = f"{run_id[:-3]}.yaml"
                text = TEMPLATE.format(
                    fname=fname, ds_key=ds_key, norm_key=norm_key, lr_key=lr_key,
                    note=ds["note"],
                    norm_desc={"zs": "per-trial channel z-score (benchmark baseline)",
                               "eaz": "per-SESSION Euclidean Alignment then the benchmark's "
                                      "per-trial channel z-score (empirical arm)",
                               "ea": "per-SESSION Euclidean Alignment (R^-1/2 X, 10% shrinkage, "
                                     "label-free, each recording aligned with its own trials) "
                                     "then a per-trial scalar scale",
                               "eamu": "per-SESSION EA with the reference covariance estimated on "
                                       "an 8-30 Hz copy of the trials, then a per-trial scalar "
                                       "scale"}[norm_key],
                    lr=lr, lr_note=("benchmark recipe value" if lr_key == "lr1e4"
                                    else "SNN-literature value (Fang et al. 2021); pilot arm"),
                    run_id=run_id, name=ds["name"], manifest=ds["manifest"],
                    n_channels=ds["n_channels"], n_classes=ds["n_classes"],
                    models=models_yaml, cross_subject=_yaml_block(ds["cross_subject"]),
                    norm=norm, out=ds["out"],
                )
                path = OUT / fname
                if args.print:
                    print(f"----- {path}\n{text}")
                else:
                    path.write_text(text, encoding="utf-8")
                written.append(path)
    if not args.print:
        for p in written:
            print("wrote", p.relative_to(ROOT))


if __name__ == "__main__":
    main()
